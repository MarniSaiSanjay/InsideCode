import ast
import io
import re
import stat
import time
import zipfile
import zlib
from collections import Counter
from dataclasses import dataclass, field
from functools import cache
from pathlib import PurePosixPath

from .config import Limits
from .languages import Language, language_for

EXCLUDED_DIRS = {
    "node_modules", "__pycache__", "site-packages", "venv", "env",
    "build", "dist", "htmlcov", "migrations", "vendor", "target", "obj", "out",
    "bower_components", "Pods", "coverage",
}  # fmt: skip
SECRET_FILES = {"secrets.py", "credentials.py", "local_settings.py"}
GENERATED_SUFFIXES = (
    "_pb2.py", "_pb2_grpc.py", ".pb.go", ".pb.cc", ".pb.h", ".min.js", ".bundle.js", ".d.ts",
    ".g.cs", ".designer.cs",
)  # fmt: skip
GENERATED_MARKERS = ("generated by", "do not edit")
MAX_CHUNK_LINES = 80
MAX_DEF_LINE = 400  # longer lines (e.g. minified code) are never definition lines
MAX_HEADER_LINES = 10  # a definition's opening `{` must appear within this many lines
MAX_END_SCAN = 5_000  # lines searched for a Ruby `end`
# Control-flow words that look like `name(` calls but never name a definition.
KEYWORDS = frozenset(
    """if else for foreach while do switch case catch try finally return throw new delete
    using lock fixed synchronized with when match loop sizeof typeof await yield function
    defer go select guard repeat elif unless until""".split()
)
ATTRIBUTE = re.compile(r"\s*(?:@\w|#\[|\[\w)")  # decorators/annotations/attributes
BRACE = re.compile(r"[{}]")
RUBY_END = re.compile(r"\s*end\b")
ONE_LINE_END = re.compile(r"\bend\s*$")
CLOSER_CHARS = " \t\n)]};,"  # a region of only these (or Ruby `end`) is a class's tail
SUPPORTED_COMPRESSION = {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}
ZIP_ERRORS = (
    zipfile.BadZipFile, zlib.error, ValueError, OSError, EOFError, OverflowError,
    NotImplementedError,
)  # fmt: skip


class ImportRejected(ValueError):
    """The archive as a whole is unsafe or exceeds an input-level limit."""


@dataclass
class SourceFile:
    path: str
    text: str


@dataclass
class ZipContents:
    files: list[SourceFile] = field(default_factory=list)
    skipped: Counter[str] = field(default_factory=Counter)


class Deadline:
    def __init__(self, seconds: float):
        self.end = time.monotonic() + seconds

    def check(self) -> None:
        if time.monotonic() > self.end:
            raise ImportRejected("Import took too long")


def _safe_parts(name: str) -> tuple[str, ...]:
    parts = PurePosixPath(name).parts
    if (
        not parts
        or "\\" in name
        or name.startswith("/")
        or any(":" in p or p == ".." for p in parts)
    ):
        raise ImportRejected(f"Unsafe path in archive: {name!r}")
    return parts


def _skip_reason(parts: tuple[str, ...], size: int, limits: Limits) -> str | None:
    if any(p.startswith(".") or p in EXCLUDED_DIRS or p.endswith(".egg-info") for p in parts[:-1]):
        return "excluded directory"
    name = parts[-1]
    if language_for(name) is None:
        return "unsupported file type"
    if name in SECRET_FILES:
        return "possible secrets file"
    if name.lower().endswith(GENERATED_SUFFIXES):
        return "generated file"
    if size > limits.max_file_bytes:
        return "file too large"
    return None


def _decode(data: bytes) -> str | None:
    if b"\0" in data:
        return None
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None
    # Match ast line numbering, which treats \r\n and \r as line breaks.
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _strip_common_root(paths: list[tuple[str, ...]]) -> int:
    roots = {p[0] for p in paths if len(p) > 1}
    return 1 if len(roots) == 1 and all(len(p) > 1 for p in paths) else 0


def read_zip(data: bytes, limits: Limits, deadline: Deadline) -> ZipContents:
    if len(data) > limits.max_zip_bytes:
        raise ImportRejected("ZIP file is larger than the upload limit")
    try:
        archive = zipfile.ZipFile(io.BytesIO(data))
    except ZIP_ERRORS as exc:
        raise ImportRejected("File is not a valid ZIP archive") from exc

    with archive:
        infos = archive.infolist()
        if len(infos) > limits.max_entries:
            raise ImportRejected("ZIP has too many entries")
        entries = []
        seen: set[str] = set()
        for info in infos:
            if info.flag_bits & 0x1:
                raise ImportRejected("Encrypted ZIP archives are not supported")
            if info.compress_type not in SUPPORTED_COMPRESSION:
                raise ImportRejected(f"Unsupported compression: {info.filename!r}")
            if stat.S_ISLNK(info.external_attr >> 16):
                raise ImportRejected(f"Symbolic links are not allowed: {info.filename!r}")
            parts = _safe_parts(info.filename)
            if info.is_dir() or parts[0] == "__MACOSX":
                continue
            key = "/".join(parts).casefold()
            if key in seen:
                raise ImportRejected(f"Duplicate path in archive: {info.filename!r}")
            seen.add(key)
            entries.append((parts, info))

        strip = _strip_common_root([parts for parts, _ in entries])
        contents = ZipContents()
        expanded = 0
        for parts, info in entries:
            deadline.check()
            reason = _skip_reason(parts, info.file_size, limits)
            if reason:
                contents.skipped[reason] += 1
                continue
            # Reads are capped at the declared size and CRC-checked, so it bounds inflation.
            expanded += info.file_size
            if expanded > limits.max_expanded_bytes:
                raise ImportRejected("ZIP expands beyond the content limit")
            try:
                with archive.open(info) as handle:
                    raw = handle.read(info.file_size)
            except ZIP_ERRORS as exc:
                raise ImportRejected(f"Corrupt ZIP entry: {info.filename!r}") from exc
            text = _decode(raw)
            if text is None:
                contents.skipped["not UTF-8 text"] += 1
                continue
            head = text[:500].lower()
            if any(marker in head for marker in GENERATED_MARKERS):
                contents.skipped["generated file"] += 1
                continue
            if len(contents.files) >= limits.max_files:
                raise ImportRejected("ZIP has more source files than the index limit")
            contents.files.append(SourceFile("/".join(parts[strip:]), text))

    if not contents.files:
        raise ImportRejected("No eligible source files found")
    return contents


@dataclass
class Chunk:
    path: str
    kind: str  # function, class, module, or lines (no definitions found or parse fallback)
    symbol: str | None
    start: int  # 1-based, inclusive
    end: int
    text: str


def _windows(lines: list[str], start: int, end: int, max_lines: int):
    for first in range(start, end + 1, max_lines):
        last = min(first + max_lines - 1, end)
        yield first, last, "\n".join(lines[first - 1 : last])


def _symbols(tree: ast.Module):
    """Yield (node, qualified name) for classes and for functions not nested in functions."""
    stack: list[tuple[ast.AST, str]] = [(tree, "")]
    while stack:
        parent, prefix = stack.pop()
        for node in ast.iter_child_nodes(parent):
            if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
                name = f"{prefix}{node.name}"
                yield node, name
                if isinstance(node, ast.ClassDef):
                    stack.append((node, f"{name}."))
            else:
                stack.append((node, prefix))


Span = tuple[int, int, str, str]  # (start, end, kind, qualified name); lines are 1-based


def _python_spans(text: str) -> list[Span] | None:
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError):
        return None
    return [
        (
            min([node.lineno] + [d.lineno for d in node.decorator_list]),
            node.end_lineno or node.lineno,
            "class" if isinstance(node, ast.ClassDef) else "function",
            name,
        )
        for node, name in _symbols(tree)
    ]


@cache
def _noise(lang: Language) -> re.Pattern[str]:
    """Comments and string literals (unterminated ones run to the end of line or file)."""
    parts = [re.escape(c) + r"[^\n]*" for c in lang.comments] + [r"/\*[\s\S]*?(?:\*/|\Z)"]
    if '"' in lang.quotes:
        parts.append(r'"""[\s\S]*?(?:"""|\Z)')
    for q in lang.quotes:
        newline = "" if q == "`" else r"\n"
        parts.append(rf"{q}(?:\\.|[^{q}\\{newline}])*{q}?")
    return re.compile("|".join(parts))


def _blank(text: str, lang: Language) -> str:
    """The source with comments and strings replaced by spaces, keeping line breaks."""
    return _noise(lang).sub(lambda m: re.sub(r"[^\n]", " ", m.group()), text)


def _definition(lang: Language, line: str) -> tuple[str, str, int] | None:
    """(kind, name, end column of the match) if the line starts a class or function."""
    if len(line) > MAX_DEF_LINE:
        return None
    for kind, patterns in (("class", lang.classes), ("function", lang.functions)):
        for pattern in patterns:
            match = pattern.match(line)
            if match and match["name"] not in KEYWORDS:
                owner = match.groupdict().get("owner")
                name = f"{owner}.{match['name']}" if owner else match["name"]
                return kind, name.replace("::", "."), match.end()
    return None


def _brace_pairs(code: list[str]) -> dict[tuple[int, int], int] | None:
    """Closing line of each `{` keyed by (line, column), or None if braces are unbalanced."""
    stack, closes = [], {}
    for i, line in enumerate(code):
        for match in BRACE.finditer(line):
            if match.group() == "{":
                stack.append((i, match.start()))
            elif not stack:
                return None
            else:
                closes[stack.pop()] = i
    return None if stack else closes


def _brace_end(code, found, closes, i: int, col: int) -> int | None:
    """Last line of the `{...}` body after a definition header, if it has one."""
    depth = 0
    for j in range(i, min(i + MAX_HEADER_LINES, len(code))):
        line = code[j]
        if j > i and (found[j] or (depth <= 0 and not line.strip())):
            return None
        for c in range(col if j == i else 0, len(line)):
            ch = line[c]
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth > 0:
                continue
            elif ch == "{":
                return closes[(j, c)]
            elif ch in ";}":
                return None  # a declaration without a body
            elif (
                ch == "="
                and line[c - 1 : c] not in tuple("=!<>+-*/%&|^:?")
                and (line[c + 1 : c + 2] not in ("=", ">"))
            ):
                return None  # an expression body such as Kotlin's `fun f() = 1`
    return None


def _end_keyword(lines: list[str], i: int) -> int | None:
    """Ruby: the line of the `end` at the definition's own indentation."""
    if ONE_LINE_END.search(lines[i]):
        return i
    indent = len(lines[i]) - len(lines[i].lstrip())
    for j in range(i + 1, min(i + MAX_END_SCAN, len(lines))):
        text = lines[j]
        if text.strip() and len(text) - len(text.lstrip()) <= indent:
            same = len(text) - len(text.lstrip()) == indent
            return j if same and RUBY_END.match(text) else None
    return None


def _is_preamble(lang: Language, lines: list[str], code: list[str], i: int) -> bool:
    raw = lines[i].lstrip()
    comment = raw and (not code[i].strip() or raw.startswith(lang.comments))
    return bool(comment or ATTRIBUTE.match(code[i]))


def _generic_spans(lang: Language, lines: list[str]) -> list[Span] | None:
    """Regex definitions with brace- or `end`-delimited bodies; None if none are found."""
    braces = lang.blocks == "braces"
    code = _blank("\n".join(lines), lang).split("\n") if braces else lines
    closes = _brace_pairs(code) if braces else {}
    if closes is None:
        return None
    found = [_definition(lang, line) for line in code]
    defs = []
    for i, definition in enumerate(found):
        if not definition:
            continue
        kind, name, col = definition
        end = _brace_end(code, found, closes, i, col) if braces else _end_keyword(lines, i)
        if end is None:
            continue
        start = i  # include directly preceding attributes and doc comments
        while start > 0 and not found[start - 1] and _is_preamble(lang, lines, code, start - 1):
            start -= 1
        defs.append((start + 1, end + 1, kind, name))

    # Like Python: qualify members of classes; skip definitions nested in functions.
    spans: list[Span] = []
    stack: list[Span] = []
    for start, end, kind, name in sorted(defs, key=lambda d: (d[0], -d[1])):
        while stack and stack[-1][1] < start:
            stack.pop()
        if stack:
            parent = stack[-1]
            if parent[2] != "class" or end > parent[1]:
                continue
            name = f"{parent[3]}.{name}"
        stack.append((start, end, kind, name))
        spans.append(stack[-1])
    return spans or None


def _region_chunks(path: str, lines: list[str], spans: list[Span], max_lines: int) -> list[Chunk]:
    """Chunks for each run of lines with the same owner: module code or the innermost span."""
    total = len(lines)
    owner: list[tuple[str, str | None]] = [("module", None)] * (total + 1)
    for start, end, kind, name in sorted(spans, key=lambda s: (s[0], -s[1])):
        owner[start : end + 1] = [(kind, name)] * (end - start + 1)

    chunks = []
    run_start = 1
    for line in range(1, total + 2):
        if line <= total and owner[line] == owner[run_start]:
            continue
        kind, symbol = owner[run_start]
        first, last = run_start, line - 1
        while first <= last and not lines[first - 1].strip():
            first += 1
        while last >= first and not lines[last - 1].strip():
            last -= 1
        for a, b, text in _windows(lines, first, last, max_lines):
            whole = (a, b) == (first, last)
            if not (whole and text.strip(CLOSER_CHARS) in ("", "end")):
                chunks.append(Chunk(path, kind, symbol, a, b, text))
        run_start = line
    return chunks


def chunk_file(file: SourceFile, max_lines: int = MAX_CHUNK_LINES) -> list[Chunk]:
    lines = file.text.split("\n")
    lang = language_for(file.path)
    spans = None
    if lang and lang.blocks == "ast":
        spans = _python_spans(file.text)
    elif lang:
        spans = _generic_spans(lang, lines)
    if spans is None:
        windows = _windows(lines, 1, len(lines), max_lines)
        return [Chunk(file.path, "lines", None, a, b, t) for a, b, t in windows if t.strip()]
    return _region_chunks(file.path, lines, spans, max_lines)
