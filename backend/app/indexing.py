EXCLUDED_DIRS = {
    "node_modules", "__pycache__", "site-packages", "venv", "env",
    "build", "dist", "htmlcov", "migrations", "vendor", "target", "obj", "out",
    "bower_components", "Pods", "coverage",
}  # fmt: skip
SECRET_FILES = {"secrets.py", "credentials.py", "local_settings.py"}
GENERATED_SUFFIXES = (
    "_pb2.py", "_pb2_grpc.py", ".pb.go", ".pb.cc", ".pb.h", ".min.js", ".bundle.js", ".d.ts",
    ".g.cs", ".designer.cs",
)  # fmt: skip
GENERATED_MARKERS = ("generated by", "do not edit")
MAX_CHUNK_LINES = 80
# Real 256 KiB files parse in ~0.1 s; crafted input can take minutes. The suggested
# progress_callback needs callback-fed parsing, which crashes in tree-sitter 0.25.
PARSE_TIMEOUT_MICROS = 2_000_000
MAX_CLASS_NESTING = 32  # deeper members stay in the outer class; names stay short
warnings.filterwarnings("ignore", "Use the progress_callback", DeprecationWarning)
# Doc comments and decorators directly above a definition.
PREAMBLE = {
    "comment", "line_comment", "block_comment", "multiline_comment", "decorator", "attribute_list",
}  # fmt: skip
FIELD_NAMES = {"property_identifier", "private_property_identifier"}
FUNCTION_VALUES = {"arrow_function", "function_expression", "generator_function"}
SIMPLE_NAME = re.compile(r"[\w$]+(?:\.[\w$]+)*")
MAX_REF_CHARS = 200  # longer import paths or called names are noise
CLOSER_CHARS = " \t\n)]};,"  # a region of only these (or Ruby `end`) is a class's tail
SUPPORTED_COMPRESSION = {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}
ZIP_ERRORS = (
    zipfile.BadZipFile, zlib.error, ValueError, OSError, EOFError, OverflowError,
    NotImplementedError,
)  # fmt: skip


class ImportRejected(ValueError):
    """The archive as a whole is unsafe or exceeds an input-level limit."""


@dataclass
class SourceFile:
    path: str
    text: str


@dataclass
class ZipContents:
    files: list[SourceFile] = field(default_factory=list)
    skipped: Counter[str] = field(default_factory=Counter)


class Deadline:
    def __init__(self, seconds: float):
        self.end = time.monotonic() + seconds

    def check(self) -> None:
        if time.monotonic() > self.end:
            raise ImportRejected("Import took too long")


def _safe_parts(name: str) -> tuple[str, ...]:
    parts = PurePosixPath(name).parts
    if (
        not parts
        or "\\" in name
        or name.startswith("/")
        or any(":" in p or p == ".." for p in parts)
    ):
        raise ImportRejected(f"Unsafe path in archive: {name!r}")
    return parts


def _skip_reason(parts: tuple[str, ...], size: int, limits: Limits) -> str | None:
    if any(p.startswith(".") or p in EXCLUDED_DIRS or p.endswith(".egg-info") for p in parts[:-1]):
        return "excluded directory"
    name = parts[-1]
    if language_for(name) is None:
        return "unsupported file type"
    if name in SECRET_FILES:
        return "possible secrets file"
    if name.lower().endswith(GENERATED_SUFFIXES):
        return "generated file"
    if size > limits.max_file_bytes:
        return "file too large"
    return None


def _decode(data: bytes) -> str | None:
    if b"\0" in data:
        return None
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None
    # Match ast line numbering, which treats \r\n and \r as line breaks.
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _strip_common_root(paths: list[tuple[str, ...]]) -> int:
    roots = {p[0] for p in paths if len(p) > 1}
    return 1 if len(roots) == 1 and all(len(p) > 1 for p in paths) else 0


def read_zip(data: bytes, limits: Limits, deadline: Deadline) -> ZipContents:
    if len(data) > limits.max_zip_bytes:
        raise ImportRejected("ZIP file is larger than the upload limit")
    try:
        archive = zipfile.ZipFile(io.BytesIO(data))
    except ZIP_ERRORS as exc:
        raise ImportRejected("File is not a valid ZIP archive") from exc

    with archive:
        infos = archive.infolist()
        if len(infos) > limits.max_entries:
            raise ImportRejected("ZIP has too many entries")
        entries = []
        seen: set[str] = set()
        for info in infos:
            if info.flag_bits & 0x1:
                raise ImportRejected("Encrypted ZIP archives are not supported")
            if info.compress_type not in SUPPORTED_COMPRESSION:
                raise ImportRejected(f"Unsupported compression: {info.filename!r}")
            if stat.S_ISLNK(info.external_attr >> 16):
                raise ImportRejected(f"Symbolic links are not allowed: {info.filename!r}")
            parts = _safe_parts(info.filename)
            if info.is_dir() or parts[0] == "__MACOSX":
                continue
            key = "/".join(parts).casefold()
            if key in seen:
                raise ImportRejected(f"Duplicate path in archive: {info.filename!r}")
            seen.add(key)
            entries.append((parts, info))

        strip = _strip_common_root([parts for parts, _ in entries])
        contents = ZipContents()
        expanded = 0
        for parts, info in entries:
            deadline.check()
            reason = _skip_reason(parts, info.file_size, limits)
            if reason:
                contents.skipped[reason] += 1
                continue
            # Reads are capped at the declared size and CRC-checked, so it bounds inflation.
            expanded += info.file_size
            if expanded > limits.max_expanded_bytes:
                raise ImportRejected("ZIP expands beyond the content limit")
            try:
                with archive.open(info) as handle:
                    raw = handle.read(info.file_size)
            except ZIP_ERRORS as exc:
                raise ImportRejected(f"Corrupt ZIP entry: {info.filename!r}") from exc
            text = _decode(raw)
            if text is None:
                contents.skipped["not UTF-8 text"] += 1
                continue
            head = text[:500].lower()
            if any(marker in head for marker in GENERATED_MARKERS):
                contents.skipped["generated file"] += 1
                continue
            if len(contents.files) >= limits.max_files:
                raise ImportRejected("ZIP has more source files than the index limit")
            contents.files.append(SourceFile("/".join(parts[strip:]), text))

    if not contents.files:
        raise ImportRejected("No eligible source files found")
    return contents


@dataclass
class Chunk:
    path: str
    kind: str  # function, class, module, or lines (no definitions found or parse fallback)
    symbol: str | None
    start: int  # 1-based, inclusive
    end: int
    text: str


Import = tuple[tuple[str, ...], bool]  # (specifiers to try in order, relative to the file)
# (calling definition: None for top-level code, "@" for a decorator; called name; on a receiver)
Call = tuple[str | None, str, bool]


@dataclass
class Facts:
    """What a file imports and calls, for the architecture view."""

    imports: list[Import] = field(default_factory=list)
    calls: dict[Call, int] = field(default_factory=dict)  # first line of each call


def _windows(lines: list[str], start: int, end: int, max_lines: int):
    for first in range(start, end + 1, max_lines):
        last = min(first + max_lines - 1, end)
        yield first, last, "\n".join(lines[first - 1 : last])


def _symbols(tree: ast.Module):
    """Yield (node, qualified name) for classes and for functions not nested in functions."""
    stack: list[tuple[ast.AST, str]] = [(tree, "")]
    while stack:
        parent, prefix = stack.pop()
        for node in ast.iter_child_nodes(parent):
            if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
                name = f"{prefix}{node.name}"
                yield node, name
                if isinstance(node, ast.ClassDef):
                    stack.append((node, f"{name}."))
            else:
                stack.append((node, prefix))


Span = tuple[int, int, str, str]  # (start, end, kind, qualified name); lines are 1-based


def _python_tree(text: str) -> ast.Module | None:
    try:
        return ast.parse(text)
    except (SyntaxError, ValueError, RecursionError):
        return None


def _python_spans(tree: ast.Module) -> list[Span]:
    return [
        (
            min([node.lineno] + [d.lineno for d in node.decorator_list]),
            node.end_lineno or node.lineno,
            "class" if isinstance(node, ast.ClassDef) else "function",
            name,
        )
        for node, name in _symbols(tree)
    ]


@cache
def _language(grammar: str) -> TSLanguage:
    """Cached for the process lifetime: a parser must never outlive its language."""
    module, _, function = grammar.partition(":")
    return TSLanguage(getattr(import_module(module), function or "language")())


def _text(src: bytes, node: Node) -> str:
    return src[node.start_byte : node.end_byte].decode("utf-8", "replace")


def _assigned_function(src: bytes, node: Node) -> str | None:
    """JS/TS `const f = () => {}`, `app.handle = function () {}` or class field `f = () => {}`."""
    if node.type in ("lexical_declaration", "variable_declaration"):
        declarators = node.named_children
        if len(declarators) == 1 and (value := declarators[0].child_by_field_name("value")):
            target = declarators[0].child_by_field_name("name")
            return _text(src, target) if value.type in FUNCTION_VALUES and target else None
    if node.type == "expression_statement" and node.named_children:
        assign = node.named_children[0]
        right = assign.child_by_field_name("right")
        if assign.type == "assignment_expression" and right and right.type in FUNCTION_VALUES:
            left = assign.child_by_field_name("left")
            if left and SIMPLE_NAME.fullmatch(name := _text(src, left)):
                return name
            prop = left and left.child_by_field_name("property")
            return _text(src, prop) if prop else None
    if node.type in ("field_definition", "public_field_definition"):  # `handle = () => {}`
        value = node.child_by_field_name("value")
        target = node.child_by_field_name("property") or node.child_by_field_name("name")
        if value and value.type in FUNCTION_VALUES and target and target.type in FIELD_NAMES:
            return _text(src, target)
    return None


def _name(src: bytes, node: Node) -> str | None:
    target = node.child_by_field_name("name")
    if target is None:  # Swift `init`, Kotlin `constructor`
        return next((c.type for c in node.children if not c.is_named and c.type.isalpha()), None)
    name = _text(src, target).split("<")[0].replace("::", ".").strip()  # `Foo<T>`, `A::B`
    if receiver := node.child_by_field_name("receiver"):  # Go `func (s *Server) Handle`
        owner = next((n for n in _descendants(receiver) if n.type == "type_identifier"), None)
        name = f"{_text(src, owner)}.{name}" if owner else name
    return name or None


def _descendants(node: Node):
    stack = [node]
    while stack:
        node = stack.pop()
        yield node
        stack.extend(reversed(node.named_children))


def _definition(lang: Language, src: bytes, node: Node) -> tuple[str, str] | None:
    if node.type in lang.classes:
        kind, name = "class", _name(src, node)
    elif node.type in lang.functions:
        kind, name = "function", _name(src, node)
    else:
        kind, name = "function", _assigned_function(src, node)
    return (kind, name) if name and not node.has_error else None


def _start(src: bytes, siblings: list[Node], i: int) -> int:
    """First row of siblings[i] with the doc comments and decorators on the lines above it.

    Siblings come from the walk: tree-sitter's parent/sibling lookups cost O(depth) each.
    """
    row = siblings[i].start_point.row
    while i > 0 and (prev := siblings[i - 1]).type in PREAMBLE and prev.end_point.row >= row - 1:
        if src[prev.start_byte - prev.start_point.column : prev.start_byte].strip():
            break  # it trails code on its line, e.g. `class A { // note`
        row, i = prev.start_point.row, i - 1
    return row


def _parse(grammar: str, src: bytes) -> Tree | None:
    try:
        return Parser(_language(grammar), timeout_micros=PARSE_TIMEOUT_MICROS).parse(src)
    except ValueError:  # timed out on pathological input
        return None


def _tree_spans(lang: Language, src: bytes, tree: Tree) -> list[Span] | None:
    """Definitions not nested in functions, with class members qualified (as for Python)."""
    root = tree.root_node
    spans: list[Span] = []
    # (parent, name prefix, start row of an enclosing `export` that the definition inherits)
    stack: list[tuple[Node, str, int | None]] = [(root, "", None)]
    while stack:
        parent, prefix, export_row = stack.pop()
        siblings = parent.named_children
        for i, node in enumerate(siblings):
            if node.type == "ERROR":
                continue
            found = _definition(lang, src, node)
            if found is None:
                export = _start(src, siblings, i) if node.type == "export_statement" else None
                stack.append((node, prefix, export))
                continue
            kind, name = found
            start = _start(src, siblings, i) if export_row is None else export_row
            end = node.end_point.row - (node.end_point.column == 0 and node.end_point.row > 0)
            spans.append((start + 1, end + 1, kind, prefix + name))
            if kind == "class" and prefix.count(".") < MAX_CLASS_NESTING:
                stack.append((node, f"{prefix}{name}.", None))
    return None if root.has_error and not spans else spans


def _owners(total: int, spans: list[Span]) -> list[tuple[str, str | None]]:
    """(kind, name) of the innermost span on each 1-based line; module code otherwise."""
    owner: list[tuple[str, str | None]] = [("module", None)] * (total + 2)
    for start, end, kind, name in sorted(spans, key=lambda s: (s[0], -s[1])):
        owner[start : end + 1] = [(kind, name)] * (end - start + 1)
    return owner


@cache
def _query(grammar: str, patterns: tuple[str, ...]) -> Query | None:
    """One query of the patterns this grammar supports."""
    lang = _language(grammar)
    valid = []
    for pattern in patterns:
        try:
            Query(lang, pattern)
            valid.append(pattern)
        except QueryError:
            pass
    return Query(lang, "\n".join(valid)) if valid else None


def _captures(grammar: str, patterns: tuple[str, ...], tree: Tree) -> dict[str, list[Node]]:
    query = _query(grammar, patterns)
    return QueryCursor(query).captures(tree.root_node) if query else {}


def _tree_facts(lang: Language, grammar: str, tree: Tree, owner: list) -> Facts:
    facts = Facts()
    for name, nodes in _captures(grammar, lang.imports, tree).items():
        for node in nodes:
            spec = node.text.decode("utf-8", "replace").strip().replace("\\", "/")
            if name in ("import", "relative") and 0 < len(spec) <= MAX_REF_CHARS:
                facts.imports.append(((spec,), name == "relative"))
    for name, nodes in _captures(grammar, lang.calls, tree).items():
        if name in ("call", "method"):
            for node in nodes:
                called = node.text.decode("utf-8", "replace")
                if len(called) <= MAX_REF_CHARS:
                    line = node.start_point.row + 1
                    _add_call(facts, (owner[line][1], called, name == "method"), line)
    return facts


def _python_facts(tree: ast.Module, owner: list) -> Facts:
    facts = Facts()
    # Decorators run where the definition is made, not inside it.
    decorators = {id(d) for n in ast.walk(tree) for d in getattr(n, "decorator_list", ())}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            facts.imports += [((a.name.replace(".", "/"),), False) for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            prefix = "./" if node.level == 1 else "../" * (node.level - 1)
            base = prefix + (node.module or "").replace(".", "/")
            for alias in node.names:
                tried = (base,) if alias.name == "*" else (f"{base.rstrip('/')}/{alias.name}", base)
                facts.imports.append((tried, node.level > 0))
        elif isinstance(node, ast.Call):
            func = node.func
            called, method = (
                (func.id, False) if isinstance(func, ast.Name)
                else (func.attr, True) if isinstance(func, ast.Attribute)
                else (None, False)
            )  # fmt: skip
            if called:
                caller = "@" if id(node) in decorators else owner[node.lineno][1]
                _add_call(facts, (caller, called, method), node.lineno)
    return facts


def _add_call(facts: Facts, call: Call, line: int) -> None:
    facts.calls[call] = min(facts.calls.get(call, line), line)


def _region_chunks(
    path: str, lines: list[str], owner: list[tuple[str, str | None]], max_lines: int
) -> list[Chunk]:
    """Chunks for each run of lines with the same owner: module code or the innermost span."""
    total = len(lines)
    chunks = []
    run_start = 1
    for line in range(1, total + 2):
        if line <= total and owner[line] == owner[run_start]:
            continue
        kind, symbol = owner[run_start]
        first, last = run_start, line - 1
        while first <= last and not lines[first - 1].strip():
            first += 1
        while last >= first and not lines[last - 1].strip():
            last -= 1
        for a, b, text in _windows(lines, first, last, max_lines):
            whole = (a, b) == (first, last)
            if not (whole and text.strip(CLOSER_CHARS) in ("", "end")):
                chunks.append(Chunk(path, kind, symbol, a, b, text))
        run_start = line
    return chunks


def parse_file(file: SourceFile, max_lines: int = MAX_CHUNK_LINES) -> tuple[list[Chunk], Facts]:
    """Searchable chunks, plus imports and calls (made inside definitions where possible)."""
    lines = file.text.split("\n")
    lang = language_for(file.path)
    spans, facts = None, Facts()
    if lang and (grammar := lang.grammars[PurePosixPath(file.path).suffix.lower()]):
        src = file.text.encode()
        if tree := _parse(grammar, src):  # keep the tree alive while walking
            spans = _tree_spans(lang, src, tree)
            facts = _tree_facts(lang, grammar, tree, _owners(len(lines), spans or []))
    elif lang and (module := _python_tree(file.text)):
        spans = _python_spans(module)
        facts = _python_facts(module, _owners(len(lines), spans))
    if spans is None:
        windows = _windows(lines, 1, len(lines), max_lines)
        chunks = [Chunk(file.path, "lines", None, a, b, t) for a, b, t in windows if t.strip()]
        return chunks, facts
    return _region_chunks(file.path, lines, _owners(len(lines), spans), max_lines), facts


def chunk_file(file: SourceFile, max_lines: int = MAX_CHUNK_LINES) -> list[Chunk]:
    return parse_file(file, max_lines)[0]
