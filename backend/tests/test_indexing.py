LIMITS = Limits()


def read(data: bytes, limits: Limits = LIMITS):
    return read_zip(data, limits, Deadline(60))


def test_admits_supported_languages_and_strips_common_root():
    files = {
        "repo/pkg/a.py": "x = 1\n",
        "repo/web/app.ts": "let x = 1\n",
        "repo/README.md": "hi",
        "repo/web/app.min.js": "x",
        "repo/vendor/lib.go": "package lib",
    }
    result = read(make_zip(files))
    assert [f.path for f in result.files] == ["pkg/a.py", "web/app.ts"]
    assert result.skipped == {
        "unsupported file type": 1,
        "generated file": 1,
        "excluded directory": 1,
    }


def test_skips_excluded_generated_secret_and_binary_files():
    result = read(
        make_zip(
            {
                "app.py": "def main(): pass\n",
                ".git/hooks/x.py": "",
                "node_modules/x/y.py": "",
                "pkg.egg-info/z.py": "",
                "api_pb2.py": "",
                "gen.py": "# Generated by tool. DO NOT EDIT.\n",
                "secrets.py": "KEY = 1\n",
                "bin.py": b"\x00\x01",
                "latin.py": "café".encode("latin-1"),
                "__MACOSX/._app.py": b"\x00",
            }
        )
    )
    assert [f.path for f in result.files] == ["app.py"]
    assert result.skipped == {
        "excluded directory": 3,
        "generated file": 2,
        "possible secrets file": 1,
        "not UTF-8 text": 2,
    }


def test_skips_oversized_file_but_keeps_others():
    limits = Limits(max_file_bytes=10)
    result = read(make_zip({"big.py": "x" * 11, "ok.py": "y = 1"}), limits)
    assert [f.path for f in result.files] == ["ok.py"]
    assert result.skipped == {"file too large": 1}


def test_keeps_utf8_bom_and_unicode():
    result = read(make_zip({"u.py": "\ufeffname = 'నమస్తే'\n".encode()}))
    assert result.files[0].text == "name = 'నమస్తే'\n"


@pytest.mark.parametrize(
    "name", ["../evil.py", "/abs.py", "a/../../evil.py", "C:/win.py", "repo/C:/x.py", "a\\b.py"]
)
def test_rejects_unsafe_paths(name):
    with pytest.raises(ImportRejected, match="Unsafe path"):
        read(make_zip({name: "x = 1"}))


def test_exclusions_apply_before_root_stripping():
    with pytest.raises(ImportRejected, match="No eligible"):
        read(make_zip({".git/a.py": "x = 1", ".git/b.py": "y = 2"}))


def test_rejects_unsupported_compression():
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_BZIP2) as archive:
        archive.writestr("a.py", "x = 1")
    with pytest.raises(ImportRejected, match="Unsupported compression"):
        read(buffer.getvalue())


def test_forged_small_size_with_matching_crc_stays_bounded():
    data = bytearray(make_zip({"a.py": "x" * 200_000}))
    crc = zlib.crc32(b"x" * 10).to_bytes(4, "little")
    local, central = data.find(b"PK\x03\x04"), data.rfind(b"PK\x01\x02")
    for crc_at, size_at in ((local + 14, local + 22), (central + 16, central + 24)):
        data[crc_at : crc_at + 4] = crc
        data[size_at : size_at + 4] = (10).to_bytes(4, "little")
    assert read(bytes(data)).files[0].text == "x" * 10


def test_rejects_symlinks():
    attrs = {"link.py": {"external_attr": (stat.S_IFLNK | 0o777) << 16}}
    with pytest.raises(ImportRejected, match="Symbolic links"):
        read(make_zip({"link.py": "/etc/passwd"}, **attrs))


def test_rejects_case_colliding_duplicates():
    with pytest.raises(ImportRejected, match="Duplicate"):
        read(make_zip({"A.py": "x = 1", "a.py": "x = 2"}))


def test_rejects_encrypted_flag():
    data = bytearray(make_zip({"a.py": "x = 1"}))
    central = data.rfind(b"PK\x01\x02")
    data[central + 8] |= 0x1
    with pytest.raises(ImportRejected, match="Encrypted"):
        read(bytes(data))


@pytest.mark.parametrize(
    ("data", "limits", "message"),
    [
        (b"not a zip", LIMITS, "not a valid ZIP"),
        (make_zip({"a.py": "x"}), Limits(max_zip_bytes=10), "upload limit"),
        (make_zip({"a.py": "x", "b.py": "y"}), Limits(max_entries=1), "too many entries"),
        (make_zip({"a.py": "x", "b.py": "y"}), Limits(max_files=1), "index limit"),
        (make_zip({"a.py": "x" * 8, "b.py": "y" * 8}), Limits(max_expanded_bytes=10), "expands"),
        (make_zip({"README.md": "hi"}), LIMITS, "No eligible"),
    ],
)
def test_rejects_input_level_limits(data, limits, message):
    with pytest.raises(ImportRejected, match=message):
        read(data, limits)


def test_header_size_lies_are_capped():
    data = bytearray(make_zip({"a.py": "x" * 100}))
    local = data.find(b"PK\x03\x04")
    central = data.rfind(b"PK\x01\x02")
    for offset in (local + 22, central + 24):
        data[offset : offset + 4] = (5).to_bytes(4, "little")
    with pytest.raises(ImportRejected, match="Corrupt"):
        read(bytes(data))


def test_deadline_is_enforced():
    with pytest.raises(ImportRejected, match="too long"):
        read_zip(make_zip({"a.py": "x"}), LIMITS, Deadline(-1))


